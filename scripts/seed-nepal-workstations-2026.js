async function seedAllNepalWorkstations() {
  console.log(`Starting to seed ${nepalWorkstations.length} workstations across whole Nepal...`)

  let created = 0
  let updated = 0

  for (const hub of nepalWorkstations) {
    const existing = await prisma.workHub.findUnique({
      where: { slug: hub.slug }
    })

    if (existing) {
      await prisma.workHub.update({
        where: { slug: hub.slug },
        data: {
          name: hub.name,
          city: hub.city,
          address: hub.address,
          description: hub.description,
          spaceType: hub.spaceType,
          rating: hub.rating,
          totalReviews: hub.totalReviews,
          openingHours: hub.openingHours,
          isVerified: hub.isVerified,
          isPartner: hub.isPartner,
          priceDaily: hub.priceDaily,
          priceMonthly: hub.priceMonthly,
          contactEmail: hub.contactEmail,
          website: hub.website,
          photoUrl: hub.photoUrl,
          facilities: hub.facilities
        }
      })
      updated++
      console.log(`[UPDATED] ${hub.city}: ${hub.name} (${hub.slug})`)
    } else {
      await prisma.workHub.create({
        data: {
          slug: hub.slug,
          name: hub.name,
          city: hub.city,
          address: hub.address,
          description: hub.description,
          spaceType: hub.spaceType,
          rating: hub.rating,
          totalReviews: hub.totalReviews,
          openingHours: hub.openingHours,
          isVerified: hub.isVerified,
          isPartner: hub.isPartner,
          priceDaily: hub.priceDaily,
          priceMonthly: hub.priceMonthly,
          contactEmail: hub.contactEmail,
          website: hub.website,
          photoUrl: hub.photoUrl,
          facilities: hub.facilities
        }
      })
      created++
      console.log(`[CREATED] ${hub.city}: ${hub.name} (${hub.slug})`)
    }
  }

  console.log(`\nAll Nepal workstations seeded successfully! Created: ${created}, Updated: ${updated}, Total: ${nepalWorkstations.length}`)
  await prisma.$disconnect()
}

seedAllNepalWorkstations().catch(err => {
  console.error("Seeding error:", err)
  process.exit(1)
})
